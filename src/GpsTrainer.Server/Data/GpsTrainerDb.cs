public sealed class GpsTrainerDb : DbContext
{
    private readonly bool _declarePostgresExtensions;

    public GpsTrainerDb(DbContextOptions<GpsTrainerDb> options) : base(options)
    {
        _declarePostgresExtensions = options.Extensions.Any(extension =>
            extension.GetType().FullName?.Contains("Npgsql", StringComparison.Ordinal) == true);
    }

    public IReadOnlyList<string> PostgresExtensionNames =>
        this.GetService<IDesignTimeModel>().Model.GetPostgresExtensions().Select(extension => extension.Name).ToArray();

    public DbSet<UserRow> Users => Set<UserRow>();
    public DbSet<CourseRow> Courses => Set<CourseRow>();
    public DbSet<RaceRow> Races => Set<RaceRow>();
    public DbSet<WaypointRow> Waypoints => Set<WaypointRow>();
    public DbSet<PositionRow> Positions => Set<PositionRow>();
    public DbSet<ActivityCodeRow> ActivityCodes => Set<ActivityCodeRow>();
    public DbSet<RacingCategoryRow> RacingCategories => Set<RacingCategoryRow>();
    public DbSet<CourseDownload> CourseDownloads => Set<CourseDownload>();
    public DbSet<RaceDownload> RaceDownloads => Set<RaceDownload>();
    public DbSet<RacePromotionRow> RacePromotions => Set<RacePromotionRow>();
    public DbSet<RaceRegistrationRow> RaceRegistrations => Set<RaceRegistrationRow>();
    public DbSet<PasswordResetRow> PasswordResets => Set<PasswordResetRow>();
    public DbSet<CourseIntervalRow> CourseIntervals => Set<CourseIntervalRow>();
    public DbSet<RoutingSettingRow> RoutingSettings => Set<RoutingSettingRow>();
    public DbSet<RevokedAuthTokenRow> RevokedAuthTokens => Set<RevokedAuthTokenRow>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        if (_declarePostgresExtensions)
        {
            modelBuilder.HasPostgresExtension("postgis");
            modelBuilder.HasPostgresExtension("timescaledb");
        }

        modelBuilder.Entity<UserRow>(e =>
        {
            e.ToTable("Users");
            e.HasKey(x => x.Login);
            e.Property(x => x.Login).HasMaxLength(32);
            e.Property(x => x.Email).HasMaxLength(50);
        });
        modelBuilder.Entity<CourseRow>(e =>
        {
            e.ToTable("Course");
            e.HasKey(x => x.CourseId);
            e.Property(x => x.Name).HasMaxLength(128);
            e.Property(x => x.Comments).HasMaxLength(256);
        });
        modelBuilder.Entity<RaceRow>(e =>
        {
            e.ToTable("Race");
            e.HasKey(x => x.RaceId);
            e.Property(x => x.Comments).HasMaxLength(256);
        });
        modelBuilder.Entity<WaypointRow>(e =>
        {
            e.ToTable("Waypoint");
            e.HasKey(x => new { x.CourseId, x.TimestampTicks });
        });
        modelBuilder.Entity<PositionRow>(e =>
        {
            e.ToTable("Position");
            e.HasKey(x => new { x.RaceId, x.TimestampTicks });
        });
        modelBuilder.Entity<ActivityCodeRow>(e =>
        {
            e.ToTable("ActivityCodes");
            e.HasKey(x => x.ActKey);
            // Keys are the site's activity codes (0 = Other). 0 is the CLR default, so EF must not treat it as "unset".
            e.Property(x => x.ActKey).ValueGeneratedNever();
        });
        modelBuilder.Entity<RacingCategoryRow>(e =>
        {
            e.ToTable("RacingCategories");
            e.HasKey(x => x.CatKey);
            e.Property(x => x.CatKey).ValueGeneratedNever();
        });
        modelBuilder.Entity<CourseDownload>(e =>
        {
            e.ToTable("CourseDownload");
            e.HasKey(x => new { x.Login, x.CourseId });
        });
        modelBuilder.Entity<RaceDownload>(e =>
        {
            e.ToTable("RaceDownload");
            e.HasKey(x => new { x.Login, x.RaceId });
        });
        modelBuilder.Entity<RacePromotionRow>(e =>
        {
            e.ToTable("RacePromotion");
            e.HasKey(x => x.RacePromotionId);
            e.Property(x => x.EntryFee).HasPrecision(19, 4);
        });
        modelBuilder.Entity<RaceRegistrationRow>(e =>
        {
            e.ToTable("RaceRegistration");
            e.HasKey(x => x.RaceRegistrationId);
        });
        modelBuilder.Entity<CourseIntervalRow>(e =>
        {
            e.ToTable("CourseInterval");
            e.HasKey(x => x.IntervalId);
            e.Property(x => x.Name).HasMaxLength(128);
        });
        modelBuilder.Entity<PasswordResetRow>(e =>
        {
            e.ToTable("PasswordReset");
            e.HasKey(x => x.Id);
        });
        modelBuilder.Entity<RoutingSettingRow>(e =>
        {
            e.ToTable("RoutingSetting");
            e.HasKey(x => x.Id);
            e.Property(x => x.Id).ValueGeneratedNever();
            e.Property(x => x.Provider).HasMaxLength(64);
        });
        modelBuilder.Entity<RevokedAuthTokenRow>(e =>
        {
            e.ToTable("RevokedAuthToken");
            e.HasKey(x => x.TokenId);
            e.Property(x => x.TokenId).HasMaxLength(128);
        });
    }
}
