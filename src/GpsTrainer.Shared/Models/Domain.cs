namespace GpsTrainer;

public sealed class UserAccount
{
    public string Login { get; set; } = "";
    public string Password { get; set; } = "";
    public string FirstName { get; set; } = "";
    public string LastName { get; set; } = "";
    public string Country { get; set; } = "US";
    public string Street { get; set; } = "";
    public string City { get; set; } = "";
    public string State { get; set; } = "";
    public string Email { get; set; } = "";
    public DateTime BirthDate { get; set; }
    public bool IsMale { get; set; } = true;
    public int RacingCategoryKey { get; set; }
    public bool IsActive { get; set; } = true;
    public string PhoneNumber { get; set; } = "";
    public bool WantsEmails { get; set; } = true;
    public DateTime ExpirationDate { get; set; }
    public double? Longitude { get; set; }
    public double? Latitude { get; set; }

    public string Gender => IsMale ? "M" : "F";
}

public sealed class UserStatus
{
    public bool IsActive { get; set; }
    public DateTime ExpirationDate { get; set; }
    public DateTime SystemTimestamp { get; set; }
    public DateTime UserTimestamp { get; set; }
}

public sealed class ActivityCode
{
    public int ActKey { get; set; }
    public string ActValue { get; set; } = "";
}

public sealed class RacingCategory
{
    public int CatKey { get; set; }
    public string CatValue { get; set; } = "";
    public bool IsMale { get; set; }
}

public sealed class Course
{
    public Guid CourseId { get; set; } = Guid.NewGuid();
    public string Name { get; set; } = "";
    public int ActivityCode { get; set; }
    public string Comments { get; set; } = "";
    public string Login { get; set; } = "";
    public int Laps { get; set; } = 1;
    public double ElapsedDistanceKm { get; set; }
    public double AltitudeGainKm { get; set; }
    public double AltitudeLossKm { get; set; }
    public bool Publish { get; set; } = true;
    public bool Approved { get; set; }
    public string City { get; set; } = "";
    public string State { get; set; } = "";
    public int Difficulty { get; set; }
    public string? Url { get; set; }
    public string? Description { get; set; }
    public DateTime? RaceDate { get; set; }
    public bool WaypointsVerified { get; set; }
    public DateTime Timestamp { get; set; } = DateTime.UnixEpoch;
    public DateTime WaypointTimestamp { get; set; } = DateTime.UnixEpoch;
    public List<Waypoint> Waypoints { get; set; } = [];
}

public sealed class Race
{
    public Guid RaceId { get; set; } = Guid.NewGuid();
    public Guid CourseId { get; set; }
    public string Comments { get; set; } = "";
    public long GoalTimeTicks { get; set; }
    public long ElapsedTimeTicks { get; set; }
    public DateTime StartTime { get; set; }
    public DateTime FinishTime { get; set; }
    public long StartPositionTicks { get; set; }
    public double ElapsedDistanceKm { get; set; }
    public double AltitudeGainKm { get; set; }
    public double AltitudeLossKm { get; set; }
    public Guid TargetRaceId { get; set; }
    public bool Publish { get; set; } = true;
    public string Login { get; set; } = "";
    public DateTime Timestamp { get; set; } = DateTime.UnixEpoch;
    public bool AutoGenerated { get; set; }
    public bool GroupRide { get; set; }

    public TimeSpan GoalTime
    {
        get => TimeSpan.FromTicks(GoalTimeTicks);
        set => GoalTimeTicks = value.Ticks;
    }
}

public sealed class Waypoint
{
    public Guid CourseId { get; set; }
    public long TimestampTicks { get; set; }
    public double Latitude { get; set; }
    public double Longitude { get; set; }
    public double HeadingDegrees { get; set; }
    public double AltitudeKm { get; set; }
    public double ElapsedDistanceKm { get; set; }
    public WaypointType WaypointType { get; set; }
    public string? TextDescription { get; set; }

    public GeoPosition Position => new(Latitude, Longitude);
    public Distance ElapsedDistance => Distance.FromKilometers(ElapsedDistanceKm);
}

public sealed class TrackPoint
{
    public Guid RaceId { get; set; }
    public long TimestampTicks { get; set; }
    public double Latitude { get; set; }
    public double Longitude { get; set; }
}

public sealed class SyncActionRecord
{
    public long RowId { get; set; }
    public ActionType Action { get; set; }
    public Guid Id { get; set; }
}
